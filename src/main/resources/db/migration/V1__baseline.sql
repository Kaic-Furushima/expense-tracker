-- Esquema original (criado antes pelo Hibernate). Bancos que ja existem sao marcados como versao 1
-- (baseline) e nao executam este arquivo; bancos novos comecam por ele.

create table categories (
    id bigint generated by default as identity primary key,
    color varchar(255),
    icon varchar(255),
    name varchar(255) not null,
    constraint uk_categories_name unique (name)
);

create table expenses (
    id bigint generated by default as identity primary key,
    amount numeric(38, 2) not null,
    date date not null,
    description varchar(255),
    invested boolean not null,
    name varchar(255) not null,
    necessary boolean not null,
    planned boolean not null,
    source varchar(255) not null,
    type enum ('EXPENSE', 'INCOME'),
    category_id bigint,
    constraint fk_expenses_category foreign key (category_id) references categories (id)
);

create table budgets (
    id bigint generated by default as identity primary key,
    amount numeric(38, 2) not null,
    category_id bigint not null,
    constraint uk_budgets_category unique (category_id),
    constraint fk_budgets_category foreign key (category_id) references categories (id)
);
