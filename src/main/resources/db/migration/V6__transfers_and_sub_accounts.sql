-- Transferencias entre contas e sub-contas ("cofrinhos": parte de uma conta cujo saldo fica separado).

alter table accounts add column parent_id bigint;
alter table accounts add constraint fk_accounts_parent foreign key (parent_id) references accounts (id);

create table transfers (
    id bigint generated by default as identity primary key,
    from_account_id bigint not null,
    to_account_id bigint not null,
    amount numeric(15, 2) not null,
    date date not null,
    description varchar(255),
    created_at timestamp not null,
    updated_at timestamp not null,
    deleted_at timestamp,
    constraint fk_transfer_from foreign key (from_account_id) references accounts (id),
    constraint fk_transfer_to foreign key (to_account_id) references accounts (id)
);
