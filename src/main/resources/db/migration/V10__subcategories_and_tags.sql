-- Subcategorias (um nivel) e etiquetas (tags) livres.

alter table categories add column parent_id bigint;
alter table categories add constraint fk_categories_parent foreign key (parent_id) references categories (id);

create table tags (
    id bigint generated by default as identity primary key,
    name varchar(40) not null,
    constraint uk_tags_name unique (name)
);

create table expense_tags (
    expense_id bigint not null,
    tag_id bigint not null,
    primary key (expense_id, tag_id),
    constraint fk_expense_tags_expense foreign key (expense_id) references expenses (id),
    constraint fk_expense_tags_tag foreign key (tag_id) references tags (id)
);
