-- Contas, formas de pagamento, pagamentos recorrentes, caixinhas, lista de desejos e configuracoes.

create table accounts (
    id bigint generated by default as identity primary key,
    name varchar(80) not null,
    type varchar(20) not null,
    color varchar(7),
    icon varchar(16),
    initial_balance numeric(38, 2) not null default 0,
    archived boolean not null default false,
    constraint uk_accounts_name unique (name)
);

create table payment_methods (
    id bigint generated by default as identity primary key,
    name varchar(60) not null,
    constraint uk_payment_methods_name unique (name)
);

alter table expenses add column account_id bigint;
alter table expenses add column payment_method_id bigint;
alter table expenses add constraint fk_expenses_account foreign key (account_id) references accounts (id);
alter table expenses add constraint fk_expenses_payment_method foreign key (payment_method_id) references payment_methods (id);

create table recurring_payments (
    id bigint generated by default as identity primary key,
    name varchar(120) not null,
    type varchar(10) not null,
    amount numeric(38, 2),
    variable_amount boolean not null default false,
    day_of_month int not null,
    account_id bigint not null,
    payment_method_id bigint,
    category_id bigint,
    necessary boolean not null default false,
    invested boolean not null default false,
    active boolean not null default true,
    start_month varchar(7) not null,
    end_month varchar(7),
    constraint fk_recurring_account foreign key (account_id) references accounts (id),
    constraint fk_recurring_payment_method foreign key (payment_method_id) references payment_methods (id),
    constraint fk_recurring_category foreign key (category_id) references categories (id)
);

create table recurring_occurrences (
    id bigint generated by default as identity primary key,
    recurring_id bigint not null,
    occurrence_month varchar(7) not null,
    due_date date not null,
    status varchar(10) not null,
    paid_date date,
    amount numeric(38, 2),
    expense_id bigint,
    constraint uk_occurrence_month unique (recurring_id, occurrence_month),
    constraint fk_occurrence_recurring foreign key (recurring_id) references recurring_payments (id),
    constraint fk_occurrence_expense foreign key (expense_id) references expenses (id)
);

create table pots (
    id bigint generated by default as identity primary key,
    name varchar(80) not null,
    color varchar(7),
    icon varchar(16),
    goal numeric(38, 2),
    mode varchar(10) not null,
    monthly_amount numeric(38, 2),
    start_month varchar(7) not null,
    active boolean not null default true,
    constraint uk_pots_name unique (name)
);

create table wish_items (
    id bigint generated by default as identity primary key,
    name varchar(120) not null,
    estimated_price numeric(38, 2),
    notes varchar(255),
    url varchar(500),
    status varchar(10) not null,
    pot_id bigint,
    real_price numeric(38, 2),
    purchase_date date,
    expense_id bigint,
    created_at date not null,
    constraint fk_wish_pot foreign key (pot_id) references pots (id),
    constraint fk_wish_expense foreign key (expense_id) references expenses (id)
);

create table pot_entries (
    id bigint generated by default as identity primary key,
    pot_id bigint not null,
    entry_date date not null,
    amount numeric(38, 2) not null,
    kind varchar(12) not null,
    note varchar(255),
    auto_month varchar(7),
    wish_item_id bigint,
    constraint uk_pot_auto_month unique (pot_id, auto_month),
    constraint fk_pot_entry_pot foreign key (pot_id) references pots (id),
    constraint fk_pot_entry_wish foreign key (wish_item_id) references wish_items (id)
);

create table app_settings (
    setting_key varchar(60) primary key,
    setting_value varchar(255) not null
);
