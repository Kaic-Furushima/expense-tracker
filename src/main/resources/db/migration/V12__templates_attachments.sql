-- Modelos de lancamento (favoritos) e anexos (foto/PDF do comprovante, guardados em base64 dentro do banco
-- para entrarem no backup).

create table expense_templates (
    id bigint generated by default as identity primary key,
    name varchar(120) not null,
    type varchar(10) not null,
    amount numeric(15, 2),
    category_id bigint,
    account_id bigint,
    payment_method_id bigint,
    description varchar(255),
    tags varchar(255),
    created_at timestamp not null,
    constraint fk_template_category foreign key (category_id) references categories (id) on delete set null,
    constraint fk_template_account foreign key (account_id) references accounts (id) on delete cascade,
    constraint fk_template_method foreign key (payment_method_id) references payment_methods (id) on delete set null
);

create table attachments (
    id bigint generated by default as identity primary key,
    expense_id bigint not null,
    file_name varchar(200) not null,
    content_type varchar(100) not null,
    size_bytes bigint not null,
    data varchar(10000000) not null,
    created_at timestamp not null,
    constraint fk_attachment_expense foreign key (expense_id) references expenses (id) on delete cascade
);
create index idx_attachments_expense on attachments (expense_id);
