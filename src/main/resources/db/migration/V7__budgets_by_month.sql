-- Orcamentos com vigencia: cada linha vale a partir de um mes e continua valendo ate a proxima linha da mesma
-- categoria. category_id nulo = limite geral do mes. amount nulo = "sem orcamento a partir deste mes".
-- A tabela e recriada porque a restricao de unicidade antiga tem nome diferente em bancos criados pelo Hibernate.

create table budgets_new (
    id bigint generated by default as identity primary key,
    category_id bigint,
    from_month varchar(7) not null,
    amount numeric(15, 2),
    constraint uk_budgets_category_month unique (category_id, from_month),
    constraint fk_budgets_category_v7 foreign key (category_id) references categories (id)
);

insert into budgets_new (category_id, from_month, amount)
select category_id, '2000-01', amount from budgets;

drop table budgets;
alter table budgets_new rename to budgets;
